"""
HARMONY-X
Dataset Recorder

Records multimodal observations generated by
the HARMONY-X perception, fusion and reasoning layers.

The session_label field records the controlled condition
used during dataset collection. This is kept separate from
the algorithm-generated emotion prediction.
"""

from pathlib import Path
from datetime import datetime
import csv


class DatasetRecorder:

    def __init__(
        self,
        output_path="data/processed/harmony_x_dataset.csv"
    ):

        self.name = "HARMONY-X Dataset Recorder"

        project_root = Path(__file__).resolve().parents[2]

        self.output_path = project_root / output_path

        self.initialized = False
        self.record_count = 0

        self.fieldnames = [
            "timestamp",

            # Controlled dataset label
            "session_label",

            # Vision
            "face_detected",
            "hands_detected",
            "pose_detected",
            "visual_confidence",

            # Expression / emotion prediction
            "emotion",
            "emotion_confidence",

            # Audio
            "speech_detected",
            "volume",
            "audio_confidence",

            # Multimodal confidence
            "overall_confidence",
            "confidence_level",
            "uncertainty",
            "uncertainty_reason",

            # Reasoning
            "action",
            "priority",
            "context_signal",

            # Temporal context
            "memory_size",
            "speech_frequency",
            "face_presence_frequency",
            "average_volume",
            "dominant_emotion",
        ]

    def initialize(self):

        self.output_path.parent.mkdir(
            parents=True,
            exist_ok=True
        )

        if not self.output_path.exists():

            with open(
                self.output_path,
                "w",
                newline="",
                encoding="utf-8"
            ) as file:

                writer = csv.DictWriter(
                    file,
                    fieldnames=self.fieldnames
                )

                writer.writeheader()

        else:

            with open(
                self.output_path,
                "r",
                encoding="utf-8"
            ) as file:

                self.record_count = max(
                    sum(1 for _ in file) - 1,
                    0
                )

        self.initialized = True

        print(
            f"{self.name}: initialized"
        )

        print(
            f"Dataset path: {self.output_path}"
        )

        print(
            f"Existing records: {self.record_count}"
        )

    def record(
        self,
        fusion_result,
        reasoning_result,
        memory_summary,
        session_label="UNKNOWN"
    ):

        if not self.initialized:

            raise RuntimeError(
                "DatasetRecorder has not been initialized."
            )

        row = {

            "timestamp":
                datetime.now().isoformat(
                    timespec="milliseconds"
                ),

            # Controlled session condition
            "session_label":
                session_label,

            # Vision
            "face_detected":
                int(fusion_result.face_detected),

            "hands_detected":
                int(fusion_result.hands_detected),

            "pose_detected":
                int(fusion_result.pose_detected),

            "visual_confidence":
                round(
                    fusion_result.visual_confidence,
                    4
                ),

            # Emotion prediction
            "emotion":
                fusion_result.emotion,

            "emotion_confidence":
                round(
                    fusion_result.emotion_confidence,
                    4
                ),

            # Audio
            "speech_detected":
                int(fusion_result.speech_detected),

            "volume":
                round(
                    fusion_result.volume,
                    4
                ),

            "audio_confidence":
                round(
                    fusion_result.audio_confidence,
                    4
                ),

            # Confidence
            "overall_confidence":
                round(
                    fusion_result.overall_confidence,
                    4
                ),

            "confidence_level":
                reasoning_result.confidence_level,

            "uncertainty":
                reasoning_result.uncertainty,

            "uncertainty_reason":
                reasoning_result.uncertainty_reason,

            # Reasoning
            "action":
                reasoning_result.action,

            "priority":
                reasoning_result.priority,

            "context_signal":
                reasoning_result.context_signal,

            # Memory
            "memory_size":
                memory_summary["memory_size"],

            "speech_frequency":
                round(
                    memory_summary["speech_frequency"],
                    4
                ),

            "face_presence_frequency":
                round(
                    memory_summary["face_presence_frequency"],
                    4
                ),

            "average_volume":
                round(
                    memory_summary["average_volume"],
                    4
                ),

            "dominant_emotion":
                memory_summary["dominant_emotion"],
        }

        with open(
            self.output_path,
            "a",
            newline="",
            encoding="utf-8"
        ) as file:

            writer = csv.DictWriter(
                file,
                fieldnames=self.fieldnames
            )

            writer.writerow(row)

        self.record_count += 1

    def status(self):

        return {
            "name": self.name,
            "initialized": self.initialized,
            "output_path": str(
                self.output_path
            ),
            "record_count": self.record_count,
        }


if __name__ == "__main__":

    recorder = DatasetRecorder()

    recorder.initialize()

    print()

    print(
        "Dataset Recorder Status:"
    )

    print(
        recorder.status()
    )
    